#!/usr/bin/env python3
"""Merge every days/day-NN-<lang>-vN/bench.json (written by bench_day.py) into benchmarks.md.

Usage: python3 lang-templates/scripts/collect_benches.py [--root DIR]

Each solution directory under <root>/days (root defaults to the current
directory) gets its own `## day-NN-<lang>-vN` section, ordered by (day, lang,
version). Sections already in benchmarks.md are kept unless a fresh bench.json
exists for that solution or its directory is gone. An unreadable bench.json is
skipped with a warning, one benchmarked with a non-default --input is skipped
with a note, and a pre-v3 bench.md without a bench.json only warns.
"""

from __future__ import annotations

import json
import platform
import re
import subprocess
import sys
from collections.abc import Callable
from datetime import date
from pathlib import Path
from typing import Any, TextIO

# Import the sibling module even under `python -P` / PYTHONSAFEPATH.
sys.path.insert(0, str(Path(__file__).resolve().parent))
from bench_day import DEFAULT_INPUT, UsageArgumentParser, render_table  # noqa: E402
from resolve_day import DIR_RE, solution_key  # noqa: E402

HEADING = "# Benchmarks"
INTRO = (
    "Sections are regenerated by `just bench <day>` / `just bench-all`; "
    "numbers from different machines are not comparable. "
    "In-process columns time `process()` only; Wall is hyperfine's whole-process "
    "time when hyperfine was installed."
)
# Any level-2 heading; only names matching DIR_RE are kept (see parse_sections).
SECTION_RE = re.compile(r"^## (\S+)[ \t]*$", re.MULTILINE)


def _run(cmd: list[str], root: Path | None = None) -> str:
    return subprocess.run(cmd, cwd=root, capture_output=True, text=True, check=True).stdout.strip()


def cpu_name() -> str:
    try:
        if platform.system() == "Darwin":
            name = _run(["sysctl", "-n", "machdep.cpu.brand_string"])
            if name:
                return name
        elif platform.system() == "Linux":
            for line in Path("/proc/cpuinfo").read_text().splitlines():
                if line.startswith("model name"):
                    return line.split(":", 1)[1].strip()
    except Exception:
        pass
    return platform.processor() or platform.machine() or "unknown CPU"


def os_name() -> str:
    system = platform.system() or "unknown OS"
    if system == "Darwin":
        system, version = "macOS", platform.mac_ver()[0]
    else:
        version = platform.release()
    parts = f"{system} {version}".strip()
    return f"{parts} ({platform.machine() or 'unknown'})"


def git_commit(root: Path | None = None) -> str:
    try:
        commit = _run(["git", "rev-parse", "--short", "HEAD"], root)
        if not commit:
            return "commit unknown"
        try:
            dirty = bool(_run(["git", "status", "--porcelain", "--untracked-files=no"], root))
        except Exception:
            dirty = False
        return f"commit {commit}" + (" (dirty)" if dirty else "")
    except Exception:
        return "commit unknown"


def metadata_line(benched: date, root: Path | None = None) -> str:
    """Best-effort one-line description of when/where the numbers were produced."""
    try:
        return f"Benchmarked {benched.isoformat()} on {cpu_name()}, {os_name()}, {git_commit(root)}"
    except Exception:
        return f"Benchmarked {benched.isoformat()}"


def sorted_sections(sections: dict[str, str]) -> dict[str, str]:
    """Order sections by (day, lang, version)."""
    return {name: sections[name] for name in sorted(sections, key=solution_key)}


def parse_sections(text: str) -> dict[str, str]:
    """Split a benchmarks.md into {day-NN-<lang>-vN: body}, body excluding the heading.

    Sections under any other `## ` heading (e.g. an old `## day-02`) are dropped.
    """
    matches = list(SECTION_RE.finditer(text))
    sections: dict[str, str] = {}
    for i, m in enumerate(matches):
        if not DIR_RE.match(m.group(1)):
            continue
        end = matches[i + 1].start() if i + 1 < len(matches) else len(text)
        sections[m.group(1)] = text[m.end():end].strip()
    return sections


def build_section(data: dict[str, Any], metadata: str) -> str:
    return f"{metadata}\n\n{render_table(data)}"


def load_bench_json(path: Path) -> dict[str, Any]:
    """Parse a bench.json; raise ValueError if it cannot be rendered."""
    try:
        data = json.loads(path.read_text(encoding="utf-8"))
    except (OSError, UnicodeDecodeError) as e:
        raise ValueError(f"cannot read: {e}") from None
    except json.JSONDecodeError as e:
        raise ValueError(f"not valid JSON: {e}") from None
    if not isinstance(data, dict) or data.get("schema") != 1:
        raise ValueError("not a schema-1 bench.json")
    try:
        render_table(data)
    except (KeyError, TypeError, ValueError, AttributeError) as e:
        raise ValueError(f"malformed ({type(e).__name__}: {e})") from None
    return data


def merge_sections(
    existing: str,
    root: Path,
    metadata: Callable[[date], str],
    existing_mtime: float | None = None,
    stderr: TextIO | None = None,
) -> dict[str, str]:
    """Merge existing benchmarks.md text with the bench.json files under root/days.

    A solution's section is replaced only when it has no section yet or its bench.json
    is newer than benchmarks.md (existing_mtime; None means every bench.json is newer).
    """
    stderr = sys.stderr if stderr is None else stderr
    sections = parse_sections(existing)
    days_dir = root / "days"
    present = {p.name for p in days_dir.glob("day-*") if p.is_dir() and DIR_RE.match(p.name)}
    sections = {name: body for name, body in sections.items() if name in present}
    for name in sorted(present, key=solution_key):
        bench = days_dir / name / "bench.json"
        if not bench.is_file():
            old = days_dir / name / "bench.md"
            if old.is_file() and (existing_mtime is None or old.stat().st_mtime > existing_mtime):
                print(
                    f"warning: days/{name}/bench.md is from the pre-v3 hyperfine-only contract; "
                    "port the solution (see README → Migrating)",
                    file=stderr,
                )
            continue
        mtime = bench.stat().st_mtime
        if name in sections and existing_mtime is not None and mtime <= existing_mtime:
            continue
        try:
            data = load_bench_json(bench)
        except ValueError as e:
            print(f"warning: skipping days/{name}/bench.json: {e}", file=stderr)
            continue
        if data.get("input") != DEFAULT_INPUT:
            print(
                f"note: days/{name}/bench.json was produced with --input {data.get('input')}; "
                "not merged into benchmarks.md",
                file=stderr,
            )
            continue
        sections[name] = build_section(data, metadata(date.fromtimestamp(mtime)))
    return sorted_sections(sections)


def render(sections: dict[str, str]) -> str:
    body = "\n\n".join(f"## {name}\n\n{text}" for name, text in sorted_sections(sections).items())
    return f"{HEADING}\n\n{INTRO}\n\n{body}\n"


def collect(root: Path, metadata: Callable[[date], str], stderr: TextIO | None = None) -> str | None:
    """Return the new benchmarks.md content, or None if there are no sections."""
    out = root / "benchmarks.md"
    existing = out.read_text(encoding="utf-8") if out.is_file() else ""
    mtime = out.stat().st_mtime if out.is_file() else None
    sections = merge_sections(existing, root, metadata, mtime, stderr)
    return render(sections) if sections else None


def main(argv: list[str] | None = None, root: Path | None = None) -> int:
    """CLI entry point; an explicit root overrides --root (used by tests)."""
    parser = UsageArgumentParser(
        prog="collect_benches.py",
        description="Merge days/*/bench.json into benchmarks.md.",
    )
    parser.add_argument(
        "--root",
        type=Path,
        default=Path.cwd(),
        help="year repo root containing days/ (default: current directory)",
    )
    args = parser.parse_args(argv)
    root = args.root if root is None else root
    content = collect(root, lambda benched: metadata_line(benched, root))
    if content is None:
        print(
            "error: no days/day-NN-<lang>-vN/bench.json files found — run `just bench <day>` first",
            file=sys.stderr,
        )
        return 1
    out = root / "benchmarks.md"
    out.write_text(content, encoding="utf-8")
    count = len(parse_sections(content))
    print(f"wrote {out.name} ({count} solutions)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
